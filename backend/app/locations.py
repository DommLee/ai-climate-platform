def list_locations(core_only: bool = False) -> List[dict]:
    items = list(LOCATION_CATALOG.values())
    if core_only:
        items = [item for item in items if item.get("core")]
    return sorted(items, key=lambda item: (item["name"].lower(), item["country"].lower()))


def get_location(location_id: str) -> dict:
    key = location_id.strip().lower()
    if key not in LOCATION_CATALOG:
        raise KeyError(location_id)
    return LOCATION_CATALOG[key]
